#!/usr/bin/env bash
# Shared validation and atomic artifact helpers for bin/fm-ci-run-check.sh: a
# raw-CI-run watch, independent of any pull or merge request. Generalizes the
# safety shape of bin/fm-pr-lib.sh's PR-poll publication (private sidecar,
# revalidated identity, atomic staged rename, one-shot retirement) to a bare
# GitHub Actions run id, so a local-only project (a direct push to a shared
# branch, with no PR in the loop) can still have its CI watched to a terminal
# result.
#
# Unlike a PR/MR poll, this poll is armed as an intentional custom check
# (bin/fm-check-register.sh: state/<id>.check.sh bound by content hash to
# state/<id>.check-trust) rather than matched against one byte-identical
# repo-committed template. fm-watch.sh's custom-check dispatch runs the
# armed check with no arguments and no reliable "$0", so there is nowhere
# else for this poll's own identity (its task id and state directory) to
# come from; the watched run identity itself (forge, repository, run id)
# still lives only in a private sidecar next to the check and is revalidated
# at poll time, never trusted from the generated script's own bytes.
#
# Retirement is one-shot and self-contained inside the generated check: on a
# terminal result it atomically claims a private receipt (a hard link, which
# only one execution can win) before printing, then removes its own check,
# trust, sidecar, and receipt. An interrupted removal leaves the receipt
# behind; the next poll execution (or the next fm-ci-run-check.sh
# registration for the same task id) finds it and finishes the cleanup
# without reporting the result a second time.

FM_CI_RUN_DATA_FORGE=
FM_CI_RUN_DATA_REPO=
FM_CI_RUN_DATA_ID=
FM_CI_RUN_POLL_DATA_TMP=
FM_CI_RUN_POLL_CHECK_TMP=
FM_CI_RUN_POLL_TRUST_TMP=
FM_CI_RUN_POLL_DATA_DEST=
FM_CI_RUN_POLL_CHECK_DEST=
FM_CI_RUN_POLL_TRUST_DEST=
FM_CI_RUN_POLL_STATE=
FM_CI_RUN_POLL_ID=
FM_CI_RUN_POLL_STATE_DEVICE=

# GitHub owner/repository rules, applied to a bare "owner/repo" string (no
# host, no pull path). Mirrors fm_pr_url_parse's GitHub owner/repo capture
# exactly: at most 39 chars for owner with no leading/trailing/doubled
# hyphen, 1-100 chars for repo excluding "." and "..", no other separator.
fm_ci_run_repo_valid() {
  local repo=${1-} pattern
  local LC_ALL=C
  pattern='^([A-Za-z0-9]|[A-Za-z0-9][A-Za-z0-9-]{0,37}[A-Za-z0-9])/([A-Za-z0-9._-]{1,100})$'
  [[ "$repo" =~ $pattern ]] || return 1
  [[ "${BASH_REMATCH[1]}" != *--* ]] || return 1
  [ "${BASH_REMATCH[2]}" != . ] && [ "${BASH_REMATCH[2]}" != .. ]
}

# A GitHub Actions run id is a positive decimal integer with no leading zero,
# the same shape fm_pr_url_parse already requires of a PR number.
fm_ci_run_id_valid() {
  local id=${1-}
  local LC_ALL=C
  [[ "$id" =~ ^[1-9][0-9]*$ ]]
}

# Sidecar layout: forge, repo (owner/name), run id, one per line.
fm_ci_run_poll_data_parse() {
  local file=$1 forge repo run_id
  FM_CI_RUN_DATA_FORGE=
  FM_CI_RUN_DATA_REPO=
  FM_CI_RUN_DATA_ID=
  [ -f "$file" ] && [ ! -L "$file" ] || return 1
  exec 8< "$file" || return 1
  IFS= read -r forge <&8 || { exec 8<&-; return 1; }
  IFS= read -r repo <&8 || { exec 8<&-; return 1; }
  IFS= read -r run_id <&8 || { exec 8<&-; return 1; }
  if IFS= read -r _extra <&8; then
    exec 8<&-
    return 1
  fi
  exec 8<&-
  [ "$forge" = github ] || return 1
  fm_ci_run_repo_valid "$repo" || return 1
  fm_ci_run_id_valid "$run_id" || return 1
  FM_CI_RUN_DATA_FORGE=$forge
  FM_CI_RUN_DATA_REPO=$repo
  FM_CI_RUN_DATA_ID=$run_id
}

# Render the generated, self-contained check.sh for one task. The run
# identity is deliberately NOT embedded here: only the task id and the state
# directory (both already path-safe, neither secret) are baked in as
# %q-quoted literals, so this generated script can locate its own private
# sidecar without relying on fm-watch.sh's custom-check dispatch passing
# arguments or preserving a meaningful "$0" - it validates a snapshot copy of
# this file, not this file itself.
fm_ci_run_poll_render() {
  local id=$1 state=$2 qid qstate
  printf -v qid '%q' "$id"
  printf -v qstate '%q' "$state"
  cat <<EOF
#!/usr/bin/env bash
# Generated by bin/fm-ci-run-check.sh for task $id. Polls a single GitHub
# Actions run to a terminal conclusion and wakes firstmate exactly once,
# independent of any pull request. The watched run identity (forge,
# repository, run id) lives only in the private sidecar next to this file and
# is revalidated here rather than trusted, so a doctored sidecar cannot
# redirect this poll at another repository. This file's exact bytes are
# hash-bound by state/$id.check-trust (bin/fm-check-register.sh contract);
# do not hand-edit it, re-run fm-ci-run-check.sh instead.
set -u
LC_ALL=C
export LC_ALL

ID=$qid
STATE_DIR=$qstate
CHECK="\$STATE_DIR/\$ID.check.sh"
TRUST="\$STATE_DIR/\$ID.check-trust"
DATA="\$STATE_DIR/\$ID.ci-run-poll"
RECEIPT="\$STATE_DIR/\$ID.ci-run-poll-retirement"

# A receipt already present means an earlier execution of this exact poll
# already claimed and reported a terminal result but was interrupted before
# it finished removing every artifact. Finish that cleanup quietly and never
# report the result a second time.
if [ -e "\$RECEIPT" ] || [ -L "\$RECEIPT" ]; then
  rm -f -- "\$CHECK" "\$TRUST" "\$DATA" "\$RECEIPT"
  exit 0
fi

[ -f "\$DATA" ] && [ ! -L "\$DATA" ] || exit 0
{ exec 3< "\$DATA"; } 2>/dev/null || exit 0
IFS= read -r forge <&3 || { exec 3<&-; exit 0; }
IFS= read -r repo <&3 || { exec 3<&-; exit 0; }
IFS= read -r run_id <&3 || { exec 3<&-; exit 0; }
if IFS= read -r _extra <&3; then
  exec 3<&-
  exit 0
fi
exec 3<&-

[ "\$forge" = github ] || exit 0
case "\$run_id" in
  [1-9]*) ;;
  *) exit 0 ;;
esac
case "\$run_id" in
  *[!0-9]*) exit 0 ;;
esac

owner=\${repo%%/*}
name=\${repo#*/}
[ "\${#owner}" -ge 1 ] && [ "\${#owner}" -le 39 ] || exit 0
case "\$owner" in
  *[!A-Za-z0-9-]*|-*|*-|*--*) exit 0 ;;
esac
[ "\${#name}" -ge 1 ] && [ "\${#name}" -le 100 ] || exit 0
case "\$name" in
  .|..|*[!A-Za-z0-9._-]*) exit 0 ;;
esac
[ "\$repo" = "\$owner/\$name" ] || exit 0

result=\$(gh run view "\$run_id" --repo "\$repo" --json status,conclusion \\
  -q 'if .status == "completed" then (.conclusion // "unknown") else "" end' 2>/dev/null) || exit 0
[ -n "\$result" ] || exit 0
case "\$result" in
  *[!A-Za-z0-9_]*) exit 0 ;;
esac

# Terminal: atomically claim the receipt (a hard link, so only one execution
# can ever win it) before printing, then retire every artifact.
umask 077
tmp=\$(mktemp "\$STATE_DIR/.fm-ci-run-poll-retirement.XXXXXX") || exit 0
if ! printf '%s\\n' "\$result" > "\$tmp" || ! chmod 0600 "\$tmp"; then
  rm -f -- "\$tmp"
  exit 0
fi
if [ -e "\$RECEIPT" ] || [ -L "\$RECEIPT" ] || ! ln -- "\$tmp" "\$RECEIPT" 2>/dev/null; then
  rm -f -- "\$tmp"
  exit 0
fi
rm -f -- "\$tmp"

printf '%s\\n' "\$result"
rm -f -- "\$CHECK" "\$TRUST" "\$DATA" "\$RECEIPT"
exit 0
EOF
}

fm_ci_run_poll_cleanup() {
  [ -z "$FM_CI_RUN_POLL_DATA_TMP" ] || rm -f -- "$FM_CI_RUN_POLL_DATA_TMP"
  [ -z "$FM_CI_RUN_POLL_CHECK_TMP" ] || rm -f -- "$FM_CI_RUN_POLL_CHECK_TMP"
  [ -z "$FM_CI_RUN_POLL_TRUST_TMP" ] || rm -f -- "$FM_CI_RUN_POLL_TRUST_TMP"
  FM_CI_RUN_POLL_DATA_TMP=
  FM_CI_RUN_POLL_CHECK_TMP=
  FM_CI_RUN_POLL_TRUST_TMP=
}

fm_ci_run_poll_revoke_final() {
  local failed=0
  if [ -e "$FM_CI_RUN_POLL_CHECK_DEST" ] || [ -L "$FM_CI_RUN_POLL_CHECK_DEST" ]; then
    rm -f -- "$FM_CI_RUN_POLL_CHECK_DEST" || failed=1
  fi
  if [ -e "$FM_CI_RUN_POLL_TRUST_DEST" ] || [ -L "$FM_CI_RUN_POLL_TRUST_DEST" ]; then
    rm -f -- "$FM_CI_RUN_POLL_TRUST_DEST" || failed=1
  fi
  if [ -e "$FM_CI_RUN_POLL_DATA_DEST" ] || [ -L "$FM_CI_RUN_POLL_DATA_DEST" ]; then
    rm -f -- "$FM_CI_RUN_POLL_DATA_DEST" || failed=1
  fi
  return "$failed"
}

# fm_ci_run_poll_prepare <state> <id> <forge> <repo> <run-id>
fm_ci_run_poll_prepare() {
  local state=$1 id=$2 forge=$3 repo=$4 run_id=$5 hash
  [ "$forge" = github ] || return 1
  fm_pr_task_id_valid "$id" || return 1
  fm_ci_run_repo_valid "$repo" || return 1
  fm_ci_run_id_valid "$run_id" || return 1

  [ ! -L "$state" ] || return 1
  mkdir -p "$state" || return 1
  [ -d "$state" ] && [ ! -L "$state" ] || return 1
  umask 077
  FM_CI_RUN_POLL_STATE=$state
  FM_CI_RUN_POLL_ID=$id
  FM_CI_RUN_POLL_DATA_DEST="$state/$id.ci-run-poll"
  FM_CI_RUN_POLL_CHECK_DEST="$state/$id.check.sh"
  FM_CI_RUN_POLL_TRUST_DEST="$state/$id.check-trust"
  FM_CI_RUN_POLL_STATE_DEVICE=$(fm_pr_file_device "$state") || return 1
  [ -n "$FM_CI_RUN_POLL_STATE_DEVICE" ] || return 1

  FM_CI_RUN_POLL_DATA_TMP=$(mktemp "$state/.fm-ci-run-poll-data.XXXXXX") || return 1
  FM_CI_RUN_POLL_CHECK_TMP=$(mktemp "$state/.fm-ci-run-poll-check.XXXXXX") || {
    fm_ci_run_poll_cleanup
    return 1
  }
  FM_CI_RUN_POLL_TRUST_TMP=$(mktemp "$state/.fm-ci-run-poll-trust.XXXXXX") || {
    fm_ci_run_poll_cleanup
    return 1
  }

  if ! printf '%s\n%s\n%s\n' "$forge" "$repo" "$run_id" > "$FM_CI_RUN_POLL_DATA_TMP" \
    || ! chmod 0600 "$FM_CI_RUN_POLL_DATA_TMP" \
    || ! fm_pr_private_file_valid "$FM_CI_RUN_POLL_DATA_TMP" 600 "$FM_CI_RUN_POLL_STATE_DEVICE" \
    || ! fm_ci_run_poll_data_parse "$FM_CI_RUN_POLL_DATA_TMP" \
    || [ "$FM_CI_RUN_DATA_FORGE" != "$forge" ] \
    || [ "$FM_CI_RUN_DATA_REPO" != "$repo" ] \
    || [ "$FM_CI_RUN_DATA_ID" != "$run_id" ]; then
    fm_ci_run_poll_cleanup
    return 1
  fi

  if ! fm_ci_run_poll_render "$id" "$state" > "$FM_CI_RUN_POLL_CHECK_TMP" \
    || ! chmod 0700 "$FM_CI_RUN_POLL_CHECK_TMP" \
    || ! fm_pr_private_file_valid "$FM_CI_RUN_POLL_CHECK_TMP" 700 "$FM_CI_RUN_POLL_STATE_DEVICE" \
    || ! bash -n "$FM_CI_RUN_POLL_CHECK_TMP"; then
    fm_ci_run_poll_cleanup
    return 1
  fi
  hash=$(fm_custom_check_sha256 "$FM_CI_RUN_POLL_CHECK_TMP") || {
    fm_ci_run_poll_cleanup
    return 1
  }
  if ! printf '%s\n%s\n' fm-custom-check-v1 "$hash" > "$FM_CI_RUN_POLL_TRUST_TMP" \
    || ! chmod 0600 "$FM_CI_RUN_POLL_TRUST_TMP" \
    || ! fm_pr_private_file_valid "$FM_CI_RUN_POLL_TRUST_TMP" 600 "$FM_CI_RUN_POLL_STATE_DEVICE"; then
    fm_ci_run_poll_cleanup
    return 1
  fi
}

fm_ci_run_poll_publish_prepared() {
  [ -n "$FM_CI_RUN_POLL_DATA_TMP" ] && [ -n "$FM_CI_RUN_POLL_CHECK_TMP" ] \
    && [ -n "$FM_CI_RUN_POLL_TRUST_TMP" ] || return 1
  fm_pr_regular_destination_on_device_or_absent "$FM_CI_RUN_POLL_DATA_DEST" "$FM_CI_RUN_POLL_STATE_DEVICE" || return 1
  fm_pr_regular_destination_on_device_or_absent "$FM_CI_RUN_POLL_TRUST_DEST" "$FM_CI_RUN_POLL_STATE_DEVICE" || return 1
  fm_pr_regular_destination_on_device_or_absent "$FM_CI_RUN_POLL_CHECK_DEST" "$FM_CI_RUN_POLL_STATE_DEVICE" || return 1

  if ! mv -f -- "$FM_CI_RUN_POLL_DATA_TMP" "$FM_CI_RUN_POLL_DATA_DEST"; then
    fm_ci_run_poll_revoke_final || true
    return 1
  fi
  FM_CI_RUN_POLL_DATA_TMP=
  if ! fm_pr_private_file_valid "$FM_CI_RUN_POLL_DATA_DEST" 600 "$FM_CI_RUN_POLL_STATE_DEVICE" \
    || ! fm_ci_run_poll_data_parse "$FM_CI_RUN_POLL_DATA_DEST"; then
    fm_ci_run_poll_revoke_final || true
    return 1
  fi

  if ! mv -f -- "$FM_CI_RUN_POLL_TRUST_TMP" "$FM_CI_RUN_POLL_TRUST_DEST"; then
    fm_ci_run_poll_revoke_final || true
    return 1
  fi
  FM_CI_RUN_POLL_TRUST_TMP=

  if ! fm_pr_regular_destination_on_device_or_absent "$FM_CI_RUN_POLL_CHECK_DEST" "$FM_CI_RUN_POLL_STATE_DEVICE" \
    || ! mv -f -- "$FM_CI_RUN_POLL_CHECK_TMP" "$FM_CI_RUN_POLL_CHECK_DEST"; then
    fm_ci_run_poll_revoke_final || true
    return 1
  fi
  FM_CI_RUN_POLL_CHECK_TMP=

  if ! fm_ci_run_poll_artifacts_valid "$FM_CI_RUN_POLL_STATE" "$FM_CI_RUN_POLL_ID"; then
    fm_ci_run_poll_revoke_final || true
    return 1
  fi
}

# fm_ci_run_poll_artifacts_valid <state> <id>: the published triple is a
# registered custom check (bin/fm-check-lib.sh's own contract) whose sidecar
# parses to a valid identity.
fm_ci_run_poll_artifacts_valid() {
  local state=$1 id=$2 state_device data
  fm_pr_task_id_valid "$id" || return 1
  [ -d "$state" ] && [ ! -L "$state" ] || return 1
  state_device=$(fm_pr_file_device "$state") || return 1
  data="$state/$id.ci-run-poll"
  fm_custom_check_registered "$state" "$id" || return 1
  fm_pr_private_file_valid "$data" 600 "$state_device" || return 1
  fm_ci_run_poll_data_parse "$data"
}

# fm_ci_run_poll_retirement_recover_one <state> <id>: called before arming a
# fresh poll. A receipt can only exist here because an earlier poll for this
# same task id already claimed and reported a terminal result but was killed
# before it finished removing its own check, trust, sidecar, and receipt (all
# four names are deterministic functions of <id>, so nothing else can be
# holding them at this path). Finish that interrupted removal so a fresh
# registration never has to reason about leftover artifacts, then arm cleanly.
fm_ci_run_poll_retirement_recover_one() {
  local state=$1 id=$2 receipt check trust data state_device artifact
  fm_pr_task_id_valid "$id" || return 1
  receipt="$state/$id.ci-run-poll-retirement"
  if [ ! -e "$receipt" ] && [ ! -L "$receipt" ]; then
    return 0
  fi
  [ -d "$state" ] && [ ! -L "$state" ] || return 1
  state_device=$(fm_pr_file_device "$state") || return 1
  fm_pr_private_file_valid "$receipt" 600 "$state_device" || return 1
  check="$state/$id.check.sh"
  trust="$state/$id.check-trust"
  data="$state/$id.ci-run-poll"
  for artifact in "$check" "$trust" "$data"; do
    if [ -e "$artifact" ] || [ -L "$artifact" ]; then
      [ -f "$artifact" ] && [ ! -L "$artifact" ] \
        && [ "$(fm_pr_file_device "$artifact")" = "$state_device" ] \
        && [ "$(fm_pr_file_link_count "$artifact")" = 1 ] || return 1
    fi
  done
  rm -f -- "$check" "$trust" "$data" "$receipt" || return 1
  [ ! -e "$check" ] && [ ! -L "$check" ] \
    && [ ! -e "$trust" ] && [ ! -L "$trust" ] \
    && [ ! -e "$data" ] && [ ! -L "$data" ] \
    && [ ! -e "$receipt" ] && [ ! -L "$receipt" ]
}
